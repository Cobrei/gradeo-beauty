import { chromium } from "playwright";
const BASE = process.env.BASE;
const b = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" });
const p = await b.newPage({ viewport: { width: 1280, height: 860 } });
const t0 = Date.now();
await p.goto(`${BASE}/login`, { timeout: 60000 });
await p.fill("#email", "dona@salao.demo"); await p.fill("#password", "gradeo123");
await p.click("button[type=submit]"); await p.waitForURL(`${BASE}/`, { timeout: 60000 });
const check = async (path, text, shot) => { const r = await p.goto(`${BASE}${path}`, { timeout: 60000 }); const body = await p.textContent("body"); const ok = r.status() === 200 && body.includes(text); console.log(`${ok ? "OK " : "FALHOU"} ${path} (${r.status()})`); await p.screenshot({ path: `e2e/prod/${shot}.png`, fullPage: false }); if (!ok) process.exitCode = 1; };
await check("/", "Clientes sumidas", "01-painel");
await check("/agenda", "Agenda", "02-agenda");
await check("/clientes", "Clientes", "03-clientes");
await check("/clientes?seg=INACTIVE", "Sumidas", "04-sumidas");
await check("/comandas", "Comandas", "05-comandas");
await check("/campanhas", "Comece por um modelo", "06-campanhas");
await check("/relatorios", "Faturamento", "07-relatorios");
await check("/comissoes", "Comissões", "08-comissoes");
await check("/configuracoes", "Configurações", "09-config");
const pub = await b.newPage({ viewport: { width: 420, height: 860 } });
const r = await pub.goto(`${BASE}/agendar/studio-bela`, { timeout: 60000 });
const pb = await pub.textContent("body"); console.log(`${r.status()===200 && pb.includes("Studio Bela") ? "OK " : "FALHOU"} /agendar/studio-bela`);
await pub.screenshot({ path: "e2e/prod/10-publico.png" });
const c = await b.newPage(); const r2 = await c.goto(`${BASE}/cadastro`); console.log(`${r2.status()===200 ? "OK " : "FALHOU"} /cadastro`);
console.log(`smoke em ${((Date.now()-t0)/1000).toFixed(1)}s`); await b.close();
